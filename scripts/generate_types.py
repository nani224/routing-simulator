#!/usr/bin/env python3
"""Generate TypeScript types from backend.phantomnet.events Pydantic models."""

from __future__ import annotations

import sys
from pathlib import Path

# Add backend directory to path
backend_path = Path(__file__).resolve().parent.parent / "backend"
if str(backend_path) not in sys.path:
    sys.path.insert(0, str(backend_path))

from phantomnet.events import EventKind  # noqa: E402


def generate_typescript() -> str:
    """Generate TypeScript declarations for EventKind, PhantomEvent, and EventBatch."""
    kinds = [f'  | "{k.value}"' for k in EventKind]
    kinds_str = "\n".join(kinds)

    kinds_array_items = ",\n".join(f'  "{k.value}"' for k in EventKind)

    ts_content = f"""/**
 * Auto-generated by scripts/generate_types.py from backend/phantomnet/events.py.
 * PHANTOMNET Canonical Event Spine TypeScript Definitions.
 *
 * DO NOT EDIT DIRECTLY. Re-generate with:
 *   python scripts/generate_types.py
 */

export type EventKind =
{kinds_str};

export interface PhantomEvent {{
  version: number;
  seq: number;
  t: number;
  kind: EventKind;
  flow_id?: string | null;
  src?: string | null;
  dst?: string | null;
  size?: number | null;
  dir?: "TX" | "RX" | string | null;
  state?: string | null;
  mask_id?: string | null;
  meta: Record<string, unknown>;
}}

export interface EventBatch {{
  type: "event_batch" | string;
  batch_seq: number;
  timestamp: number;
  run_id: string;
  events: PhantomEvent[];
}}

export const EVENT_KINDS: readonly EventKind[] = [
{kinds_array_items}
] as const;
"""
    return ts_content


def main() -> None:
    repo_root = Path(__file__).resolve().parent.parent
    targets = [
        repo_root / "frontend" / "src" / "types" / "events.ts",
        repo_root / "spec" / "events.d.ts",
    ]

    ts_code = generate_typescript()

    for target in targets:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(ts_code, encoding="utf-8")
        print(f"Generated: {target}")


if __name__ == "__main__":
    main()
